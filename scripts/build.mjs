// npm run build — tokens (DTCG 2025.10) → dist/<brand>/ via Style Dictionary v5.
// Per brand: css/<mode>.css, css/density-<d>.css, css/tokens.css (bundle), tailwind/theme.css,
// json/<mode>.json, json/density-compact.json, figma/variables.json, meta.json.
// Also regenerates the YAML front matter of brands/<id>/DESIGN.md from the tokens.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { ROOT, MODES, DENSITIES, listBrands, sources, writeFile, writeAggregates } from './lib.mjs';

const version = fs.readFileSync(path.join(ROOT, 'VERSION'), 'utf8').trim();
const PREFIX = 'aid';
const header = (brand, scope) => () => [
  `AID brand library v${version} · brand: ${brand.id} · ${scope}`,
  'Generated by scripts/build.mjs from DTCG tokens. Do not edit; edit tokens and rebuild.',
  'PLACEHOLDER values: no visual decisions have been made yet.',
];
const fromFile = (t, part) => t.filePath.split(path.sep).join('/').includes(part);

/** Run Style Dictionary for one brand × mode × density; returns the transformed tokens. */
async function runSD(brand, mode, density, files) {
  const sd = new StyleDictionary({
    source: sources(brand, mode, density),
    parsers: ['aid/dtcg-file'],
    log: { verbosity: 'silent', warnings: 'error' },
    platforms: {
      web: { transformGroup: 'css', prefix: PREFIX, buildPath: path.join(ROOT, 'dist', brand.id) + '/', files },
    },
  }, { init: false });
  await sd.init(); // explicit init so collisions/broken refs throw a catchable error
  await sd.buildAllPlatforms();
  return (await sd.getPlatformTokens('web')).allTokens;
}

// Tailwind v4: map semantic tokens into Tailwind namespaces as references to --aid-* vars,
// so one theme file serves every mode and density (switching happens in the CSS variables).
function tailwindTheme(tokens, brand) {
  const v = (t) => `var(--${t.name})`;
  const lines = [];
  for (const t of tokens) {
    const p = t.path;
    if (p[0] === 'color' && fromFile(t, '/modes/')) lines.push(`--color-${p.slice(1).join('-')}: ${v(t)};`);
    else if (['status', 'focus', 'symbology', 'classification'].includes(p[0]) && t.$value?.toString().startsWith('#'))
      lines.push(`--color-${p.join('-')}: ${v(t)};`);
    else if (p[0] === 'space' && fromFile(t, '/density/')) lines.push(`--spacing-${p.slice(1).join('-')}: ${v(t)};`);
    else if (p[0] === 'radius' && fromFile(t, '/semantic/')) lines.push(`--radius-${p[1]}: ${v(t)};`);
    else if (p[0] === 'font' && p[1] === 'family') lines.push(`--font-${p[2]}: ${v(t)};`);
    else if (p[0] === 'brand' && p[1] === 'font') lines.push(`--font-${p[2]}: ${v(t)};`);
    else if (p[0] === 'motion' && p[1] === 'easing') lines.push(`--ease-${p[2]}: ${v(t)};`);
    else if (p[0] === 'type') {
      const suffix = { size: '', 'line-height': '--line-height', weight: '--font-weight' }[p[2]];
      if (suffix !== undefined) lines.push(`--text-${p[1]}${suffix}: ${v(t)};`);
    }
  }
  return [
    `/* AID brand library v${version} · brand: ${brand.id} · Tailwind v4 theme.`,
    ' * Load after css/tokens.css. Values are references, so mode/density switching keeps working.',
    ' * --color-*: initial removes Tailwind\'s default palette: only semantic colours exist. */',
    '@theme inline {',
    '  --color-*: initial;',
    ...lines.map((l) => `  ${l}`),
    '}',
    '',
  ].join('\n');
}

// Figma-variables-friendly JSON: collections → modes → variables (with aliases kept).
const COLLECTIONS = [
  ['Primitives', (t) => fromFile(t, '/primitives/') || fromFile(t, 'palette.tokens.json')],
  ['Brand', (t) => fromFile(t, 'brand.tokens.json')],
  ['Color', (t) => fromFile(t, '/modes/')],
  ['Density', (t) => fromFile(t, '/density/')],
  ['Semantic', (t) => fromFile(t, '/semantic/')],
  ['Protected', (t) => fromFile(t, '/protected/')],
];
function figmaValue(t) {
  const val = t.$value;
  const alias = typeof t.original.$value === 'string' && /^\{[^}]+\}$/.test(t.original.$value)
    ? t.original.$value.slice(1, -1).split('.').join('/') : undefined;
  let type = 'STRING';
  let value = val;
  if (typeof val === 'number') type = 'FLOAT';
  else if (/^#[0-9a-f]{3,8}$/i.test(val)) type = 'COLOR';
  else if (/^-?[\d.]+px$/.test(val)) [type, value] = ['FLOAT', parseFloat(val)];
  else if (/^[\d.]+s$/.test(val)) [type, value] = ['FLOAT', Math.round(parseFloat(val) * 1000)]; // ms
  return { type, entry: alias ? { value, alias } : { value } };
}
function addFigma(store, tokens, modeName, axis) {
  for (const t of tokens) {
    const [collection] = COLLECTIONS.find(([, test]) => test(t)) ?? ['Other'];
    if ((axis === 'density') !== (collection === 'Density')) continue; // density values come from density runs only
    const key = axis === 'density' ? modeName : collection === 'Color' ? modeName : 'value';
    const name = t.path.join('/');
    const { type, entry } = figmaValue(t);
    store[collection] ??= {};
    store[collection][name] ??= { name, type, description: t.$description ?? '', valuesByMode: {} };
    store[collection][name].valuesByMode[key] = entry;
  }
}

// DESIGN.md (Google Labs format) front matter, generated from light-mode tokens.
function designFrontMatter(brand, tokens) {
  const byPath = Object.fromEntries(tokens.map((t) => [t.path.join('.'), t.$value]));
  const q = (s) => JSON.stringify(String(s));
  const colors = {
    primary: 'brand.color.primary.base', 'on-primary': 'brand.color.primary.on', 'primary-subtle': 'brand.color.primary.subtle',
    accent: 'brand.color.accent.base', canvas: 'color.surface.canvas', surface: 'color.surface.default',
    'on-surface': 'color.text.primary', 'text-secondary': 'color.text.secondary', border: 'color.border.default',
    danger: 'color.feedback.danger.fg',
  };
  const roles = ['display', 'heading-1', 'heading-2', 'heading-3', 'body', 'body-small', 'label', 'caption'];
  const out = [
    '---',
    '# GENERATED by `npm run build` from tokens (light mode, comfortable density). Do not edit this block;',
    '# edit brands/<id>/tokens/*.tokens.json or core/tokens/ and rebuild. PLACEHOLDER values.',
    'version: alpha',
    `name: ${q(brand.name)}`,
    `description: ${q(`DRAFT. ${brand.description}`)}`,
    'colors:',
    ...Object.entries(colors).map(([k, p]) => `  ${k}: ${q(byPath[p])}`),
    'typography:',
    ...roles.flatMap((r) => [
      `  ${r}:`,
      `    fontFamily: ${q(byPath[`type.${r}.family`])}`,
      `    fontSize: ${byPath[`type.${r}.size`]}`,
      `    fontWeight: ${byPath[`type.${r}.weight`]}`,
      `    lineHeight: ${byPath[`type.${r}.line-height`]}`,
    ]),
    'rounded:',
    ...['sm', 'md', 'lg', 'xl', 'full'].map((k) => `  ${k}: ${byPath[`radius.${k}`]}`),
    'spacing:',
    ...Object.entries({ xs: 1, sm: 2, md: 4, lg: 6, xl: 10 }).map(([k, n]) => `  ${k}: ${byPath[`space.${n}`]}`),
    'components:',
    '  button-primary:',
    '    backgroundColor: "{colors.primary}"',
    '    textColor: "{colors.on-primary}"',
    '    rounded: "{rounded.md}"',
    `    height: ${byPath['size.control.height']}`,
    '  card:',
    '    backgroundColor: "{colors.surface}"',
    '    textColor: "{colors.on-surface}"',
    '    rounded: "{rounded.lg}"',
    '    padding: "{spacing.lg}"',
    '---',
    '',
  ];
  return out.join('\n');
}
function writeDesignMd(brand, tokens) {
  const file = path.join(brand.dir, 'DESIGN.md');
  const fm = designFrontMatter(brand, tokens);
  const body = fs.existsSync(file)
    ? fs.readFileSync(file, 'utf8').replace(/^---\n[\s\S]*?\n---\n\n?/, '')
    : `# ${brand.name} · DESIGN (DRAFT)\n`;
  fs.writeFileSync(file, fm + '\n' + body);
}

function meta(brand, tokens) {
  const css = (t) => `--${t.name}`;
  const colour = (t) => typeof t.$value === 'string' && t.$value.startsWith('#');
  const groups = {};
  const add = (g, t) => (groups[g] ??= []).push(css(t));
  for (const t of tokens.filter(colour)) {
    const p = t.path;
    if (p[0] === 'color' && fromFile(t, '/modes/')) add(`color.${p[1]}`, t);
    else if (p[0] === 'brand') add('brand roles', t);
    else if (p[0] === 'palette') add('brand palette', t);
    else if (fromFile(t, '/protected/')) add(`${p[0]} (protected)`, t);
  }
  return {
    id: brand.id, name: brand.name, role: brand.role, modules: brand.modules ?? [],
    swatches: groups,
    typeRoles: [...new Set(tokens.filter((t) => t.path[0] === 'type').map((t) => t.path[1]))],
    spacing: tokens.filter((t) => t.path[0] === 'space' && fromFile(t, '/density/')).map(css),
  };
}

export async function build() {
  const brands = listBrands();
  fs.rmSync(path.join(ROOT, 'dist'), { recursive: true, force: true });
  for (const brand of brands) {
    const figma = {};
    const sel = (axis, v) => `[data-brand="${brand.id}"][data-${axis}="${v}"]`;
    let light;
    for (const mode of MODES) {
      const tokens = await runSD(brand, mode, 'comfortable', [
        { destination: `css/${mode}.css`, format: 'css/variables', options: { selector: sel('mode', mode), outputReferences: true, fileHeader: header(brand, `mode: ${mode}`) } },
        { destination: `json/${mode}.json`, format: 'json/flat' },
        ...(mode === 'light'
          ? [{ destination: 'css/density-comfortable.css', format: 'css/variables', filter: (t) => fromFile(t, '/density/'), options: { selector: sel('density', 'comfortable'), fileHeader: header(brand, 'density: comfortable') } },
             { destination: 'tailwind/theme.css', format: 'aid/tailwind-theme', options: { brand } }]
          : []),
      ]);
      addFigma(figma, tokens, mode, 'mode');
      if (mode === 'light') { light = tokens; addFigma(figma, tokens, 'comfortable', 'density'); }
    }
    const compact = await runSD(brand, 'light', 'compact', [
      { destination: 'css/density-compact.css', format: 'css/variables', filter: (t) => fromFile(t, '/density/'), options: { selector: sel('density', 'compact'), fileHeader: header(brand, 'density: compact') } },
      { destination: 'json/density-compact.json', format: 'json/flat', filter: (t) => fromFile(t, '/density/') },
    ]);
    addFigma(figma, compact, 'compact', 'density');

    const out = path.join(ROOT, 'dist', brand.id);
    // Bundle: modes first, density last (equal specificity, so density overrides the defaults).
    const bundle = [...MODES.map((m) => `css/${m}.css`), ...DENSITIES.map((d) => `css/density-${d}.css`)]
      .map((f) => fs.readFileSync(path.join(out, f), 'utf8')).join('\n');
    writeFile(path.join(out, 'css/tokens.css'), bundle);
    writeFile(path.join(out, 'figma/variables.json'), JSON.stringify({
      note: 'Figma-variables-friendly export. One collection per tier; Color has light/dark/night modes, Density has comfortable/compact. alias = Figma variable name to bind to. FLOAT dimensions are px, durations ms.',
      library: version, brand: brand.id,
      collections: Object.entries(figma).map(([name, vars]) => ({
        name, modes: [...new Set(Object.values(vars).flatMap((x) => Object.keys(x.valuesByMode)))], variables: Object.values(vars),
      })),
    }, null, 2) + '\n');
    writeFile(path.join(out, 'meta.json'), JSON.stringify(meta(brand, light), null, 2) + '\n');
    writeDesignMd(brand, light);
    console.log(`✔ ${brand.id.padEnd(16)} ${MODES.length} modes × ${DENSITIES.length} densities · ${light.length} tokens → dist/${brand.id}/`);
  }
  writeAggregates();
  console.log(`✔ dist/all.css + dist/manifest.js (${brands.length} brands) · library v${version}`);
}

// File-level $description documents each source file; drop it before merging so it is not a collision.
StyleDictionary.registerParser({
  name: 'aid/dtcg-file',
  pattern: /\.tokens\.json$/,
  parser: ({ contents }) => {
    const { $description, ...tokens } = JSON.parse(contents);
    return tokens;
  },
});
StyleDictionary.registerFormat({ name: 'aid/tailwind-theme', format: ({ dictionary, options }) => tailwindTheme(dictionary.allTokens, options.brand) });

if (import.meta.url === pathToFileURL(process.argv[1]).href) await build();
