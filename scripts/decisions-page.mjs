// npm run decisions
// Renders docs/DECISIONS.md (the source) into docs/decisions.html, a page the brand owner can read and act on.
// Open lines:  - area · question · recommendation · waiting on · evidence
// Log lines:   date · decision · why · alternatives rejected
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(ROOT, 'docs/DECISIONS.md'), 'utf8');
const section = (name) => (src.split(/^## /m).find((s) => s.startsWith(name)) ?? '').split('\n').slice(1);
const fields = (line) => line.split(' · ').map((s) => s.trim());
const esc = (s = '') => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

const open = section('Open').filter((l) => l.startsWith('- ')).map((l) => {
  const [area, question, recommendation, waitingOn, evidence] = fields(l.slice(2));
  return { area, question, recommendation, waitingOn, evidence };
});
const log = section('Log').filter((l) => /^\d{4}-\d{2}-\d{2}/.test(l)).map((l) => {
  const [date, decision, why, rejected] = fields(l);
  return { date, decision, why, rejected };
}).reverse();

const owner = (o) => (/leadership/i.test(o.waitingOn) ? 'leadership' : 'you');
const groups = [
  ['you', 'Waiting on you', 'Decide these as the work reaches them.'],
  ['leadership', 'Waiting on leadership', 'Answers come from the leadership questionnaire.'],
];
const card = (o) => `
      <article class="card">
        <span class="area">${esc(o.area)}</span>
        <h3>${esc(o.question)}</h3>
        <dl>
          <dt>Recommendation</dt><dd>${esc(o.recommendation)}</dd>
          <dt>Decides</dt><dd>${esc(o.waitingOn)}</dd>
          <dt>Evidence</dt><dd><code>${esc(o.evidence)}</code></dd>
        </dl>
      </article>`;
const updated = log[0]?.date ?? '';

const html = `<meta charset="utf-8">
<title>AID Decision Tracker</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="claude:viewport-fit-sides" content="cover">
<style>
/* Generated by scripts/decisions-page.mjs from docs/DECISIONS.md. Do not edit by hand. */
:root{--bg:#F5F5F2;--surface:#FFF;--ink:#16191C;--muted:#5B636B;--line:#DADDD8;--you:#9A5200;--you-tint:#FCEBD5;--lead:#1F5FAE;--lead-tint:#DDE8F7;--done:#1E7436;
  --sans:system-ui,-apple-system,"Segoe UI",sans-serif;--mono:ui-monospace,"SF Mono",Menlo,monospace}
@media (prefers-color-scheme:dark){:root:not([data-theme="light"]){--bg:#111416;--surface:#181C1F;--ink:#E6E9EB;--muted:#9AA3AB;--line:#2C3338;--you:#F2A54A;--you-tint:#3A2A15;--lead:#7EAEF0;--lead-tint:#182B44;--done:#66C27E;color-scheme:dark}}
:root[data-theme="dark"]{--bg:#111416;--surface:#181C1F;--ink:#E6E9EB;--muted:#9AA3AB;--line:#2C3338;--you:#F2A54A;--you-tint:#3A2A15;--lead:#7EAEF0;--lead-tint:#182B44;--done:#66C27E;color-scheme:dark}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--ink);font:15px/1.55 var(--sans);padding-left:max(16px,env(safe-area-inset-left,0px));padding-right:max(16px,env(safe-area-inset-right,0px))}
main{max-width:1080px;margin:0 auto;padding-block:40px 80px;display:flex;flex-direction:column;gap:40px}
h1{font-size:clamp(1.8rem,4vw,2.6rem);line-height:1.1;margin:0;text-wrap:balance}
h2{font-size:1.35rem;margin:0}
h3{font-size:1.02rem;line-height:1.35;margin:0;text-wrap:balance}
p{margin:0;max-width:68ch}
.muted{color:var(--muted)}
.label{font:500 .75rem/1 var(--mono);letter-spacing:.06em;text-transform:uppercase;color:var(--muted)}
.counts{display:flex;flex-wrap:wrap;gap:12px}
.count{background:var(--surface);border:1px solid var(--line);border-radius:6px;padding:12px 16px;min-width:150px;display:flex;flex-direction:column;gap:6px}
.count b{font:600 1.6rem/1 var(--mono);font-variant-numeric:tabular-nums}
.count.you b{color:var(--you)} .count.lead b{color:var(--lead)} .count.done b{color:var(--done)}
section{display:flex;flex-direction:column;gap:14px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:12px}
.card{background:var(--surface);border:1px solid var(--line);border-radius:6px;padding:16px;display:flex;flex-direction:column;gap:10px;min-width:0}
.you .card{border-top:3px solid var(--you)} .leadership .card{border-top:3px solid var(--lead)}
.area{align-self:flex-start;font:500 .72rem/1 var(--mono);padding:4px 8px;border-radius:999px}
.you .area{color:var(--you);background:var(--you-tint)} .leadership .area{color:var(--lead);background:var(--lead-tint)}
dl{margin:0;display:grid;grid-template-columns:auto minmax(0,1fr);gap:4px 12px;font-size:.92rem}
dt{color:var(--muted)} dd{margin:0}
code{font:.8rem var(--mono);word-break:break-word;color:var(--muted)}
.tbl{overflow-x:auto;border:1px solid var(--line);border-radius:6px;background:var(--surface)}
table{border-collapse:collapse;width:100%;font-size:.92rem}
th,td{text-align:left;vertical-align:top;padding:10px 12px;border-bottom:1px solid var(--line)}
th{font:500 .72rem var(--mono);letter-spacing:.05em;text-transform:uppercase;color:var(--muted)}
tr:last-child td{border-bottom:0}
td.date{font-family:var(--mono);font-variant-numeric:tabular-nums;white-space:nowrap;color:var(--muted)}
td.rej{color:var(--muted)}
</style>
<main>
  <header style="display:flex;flex-direction:column;gap:12px">
    <span class="label">AID brand system · last decision ${esc(updated)}</span>
    <h1>Decision tracker</h1>
    <p class="muted">Every brand and design decision, with the reason and what was rejected, plus the decisions still open. Generated from <code>docs/DECISIONS.md</code>.</p>
    <div class="counts">
      <div class="count you"><span class="label">Waiting on you</span><b>${open.filter((o) => owner(o) === 'you').length}</b></div>
      <div class="count lead"><span class="label">Waiting on leadership</span><b>${open.filter((o) => owner(o) === 'leadership').length}</b></div>
      <div class="count done"><span class="label">Decided</span><b>${log.length}</b></div>
    </div>
  </header>
${groups.map(([key, title, note]) => `
  <section class="${key}">
    <div><h2>${title}</h2><p class="muted">${note}</p></div>
    <div class="grid">${open.filter((o) => owner(o) === key).map(card).join('')}
    </div>
  </section>`).join('')}
  <section>
    <div><h2>Decided</h2><p class="muted">Newest first.</p></div>
    <div class="tbl"><table>
      <thead><tr><th>Date</th><th>Decision</th><th>Why</th><th>Rejected</th></tr></thead>
      <tbody>${log.map((d) => `
        <tr><td class="date">${esc(d.date)}</td><td>${esc(d.decision)}</td><td>${esc(d.why)}</td><td class="rej">${esc(d.rejected)}</td></tr>`).join('')}
      </tbody>
    </table></div>
  </section>
</main>
`;

fs.writeFileSync(path.join(ROOT, 'docs/decisions.html'), html);
console.log(`✔ docs/decisions.html · ${open.length} open · ${log.length} decided`);
