// Shared helpers for build, export and check. Must never name a specific brand:
// this file ships inside every single-brand export.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MODES = ['light', 'dark', 'night'];
export const DENSITIES = ['comfortable', 'compact'];
export const PROTECTED = ['status', 'focus', 'symbology', 'classification'];
export const OPTIONAL_MODULES = ['symbology', 'classification']; // protected, opt-in per brand
export const BRAND_NAMESPACES = ['brand', 'palette']; // the only top-level groups a brand may define

export const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
export const writeFile = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};
export const tokenFiles = (dir) =>
  fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.tokens.json')).sort().map((f) => path.join(dir, f)) : [];

/** Every brand folder that has a brand.json, as manifests. */
export function listBrands(root = ROOT) {
  const dir = path.join(root, 'brands');
  return fs
    .readdirSync(dir)
    .filter((d) => fs.existsSync(path.join(dir, d, 'brand.json')))
    .sort()
    .map((d) => ({ ...readJson(path.join(dir, d, 'brand.json')), dir: path.join(dir, d) }));
}

/** Core protected files a brand receives: always-on ones plus the optional modules it lists. */
export function protectedFiles(brand, root = ROOT) {
  return tokenFiles(path.join(root, 'core/tokens/protected')).filter((f) => {
    const name = path.basename(f, '.tokens.json');
    return !OPTIONAL_MODULES.includes(name) || (brand.modules ?? []).includes(name);
  });
}

/**
 * Source order for one brand × mode × density. Later files win on collision, so the
 * protected namespaces load last: even if a brand tried to override them, core wins.
 */
export function sources(brand, mode, density, root = ROOT) {
  const core = (p) => tokenFiles(path.join(root, 'core/tokens', p));
  return [
    ...core('primitives'),
    ...tokenFiles(path.join(brand.dir, 'tokens')),
    ...core('semantic'),
    path.join(root, 'core/tokens/modes', `${mode}.tokens.json`),
    path.join(root, 'core/tokens/density', `${density}.tokens.json`),
    ...protectedFiles(brand, root),
  ];
}

/** Walk a DTCG tree and yield [dotPath, token] for every token (object with $value). */
export function* walkTokens(node, trail = []) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$') || typeof val !== 'object' || val === null) continue;
    if ('$value' in val) yield [[...trail, key].join('.'), val];
    else yield* walkTokens(val, [...trail, key]);
  }
}

/** Recursively list files under dir (skips node_modules and dotfiles). */
export function listFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    if (e.name.startsWith('.') || e.name === 'node_modules') return [];
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(p) : [p];
  });
}

/** Lower-case hex values written in a brand's own token files. */
export function brandHexes(brand) {
  const hexes = new Set();
  for (const f of tokenFiles(path.join(brand.dir, 'tokens')))
    for (const [, t] of walkTokens(readJson(f))) if (t.$value?.hex) hexes.add(t.$value.hex.toLowerCase());
  return hexes;
}

/**
 * dist/all.css + dist/manifest.js: what the preview page loads. Built from whatever
 * dist/<brand>/meta.json files exist, so it also works inside a single-brand export.
 */
export function writeAggregates(root = ROOT) {
  const dist = path.join(root, 'dist');
  const metas = fs
    .readdirSync(dist)
    .filter((d) => fs.existsSync(path.join(dist, d, 'meta.json')))
    .sort()
    .map((d) => readJson(path.join(dist, d, 'meta.json')));
  const css = metas.map((m) => fs.readFileSync(path.join(dist, m.id, 'css/tokens.css'), 'utf8')).join('\n');
  writeFile(path.join(dist, 'all.css'), css);
  const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
  const manifest = { version, modes: MODES, densities: DENSITIES, brands: metas };
  writeFile(path.join(dist, 'manifest.js'), `// Generated by scripts/build.mjs. Do not edit.\nwindow.AID_LIBRARY = ${JSON.stringify(manifest, null, 2)};\n`);
}

/**
 * Isolation scan for a single-brand export: no file may name another brand (id or display
 * name) or contain a hex value that only another brand uses. Returns a list of problems.
 */
export function scanIsolation(outDir, brand, allBrands) {
  const others = allBrands.filter((b) => b.id !== brand.id);
  const allowedHex = new Set([...brandHexes(brand), ...coreHexes()]);
  const foreignHex = new Set(others.flatMap((b) => [...brandHexes(b)]).filter((h) => !allowedHex.has(h)));
  const terms = others.flatMap((b) => (b.role === 'legal-parent' ? [b.id] : [b.id, b.name]));
  const problems = [];
  for (const file of listFiles(outDir)) {
    const rel = path.relative(outDir, file);
    for (const t of terms) if (rel.includes(t)) problems.push(`${rel}: path names "${t}"`);
    if (!/\.(json|css|js|mjs|md|html|svg|txt|yaml|yml)$/.test(file) && path.basename(file) !== 'VERSION') continue;
    const text = fs.readFileSync(file, 'utf8');
    const lower = text.toLowerCase();
    for (const t of terms) if (text.includes(t)) problems.push(`${rel}: mentions "${t}"`);
    for (const h of foreignHex) if (lower.includes(h)) problems.push(`${rel}: contains ${h} (another brand's colour)`);
  }
  return problems;
}

export function coreHexes(root = ROOT) {
  const hexes = new Set();
  for (const f of listFiles(path.join(root, 'core/tokens')).filter((f) => f.endsWith('.tokens.json')))
    for (const [, t] of walkTokens(readJson(f))) if (t.$value?.hex) hexes.add(t.$value.hex.toLowerCase());
  return hexes;
}
