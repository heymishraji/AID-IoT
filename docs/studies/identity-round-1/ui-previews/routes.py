"""Builds routes.css: each identity-round-1 colour route as an override of the brand library's
brand roles and neutral scale. Everything else (semantic tokens, status, focus, night) stays the library's.
Run: python3 routes.py  → writes routes.css next to this file and prints a contrast report."""
import math, os
def to_srgb(L, C, h):
    a, b = C * math.cos(math.radians(h)), C * math.sin(math.radians(h))
    l_, m_, s_ = L + .3963377774*a + .2158037573*b, L - .1055613458*a - .0638541728*b, L - .0894841775*a - 1.2914855480*b
    l, m, s = l_**3, m_**3, s_**3
    rgb = (4.0767416621*l - 3.3077115913*m + .2309699292*s, -1.2684380046*l + 2.6097574011*m - .3413193965*s, -.0041960863*l - .7034186147*m + 1.7076147010*s)
    return rgb
def gamut(L, C, h):
    while C > 0:
        if all(-1e-4 <= v <= 1 + 1e-4 for v in to_srgb(L, C, h)): break
        C -= .002
    enc = lambda x: 12.92*x if x <= .0031308 else 1.055*x**(1/2.4) - .055
    return '#%02X%02X%02X' % tuple(round(min(max(enc(min(max(v, 0), 1)), 0), 1)*255) for v in to_srgb(L, max(C, 0), h))
def lum(hx):
    v = [int(hx[i:i+2], 16)/255 for i in (1, 3, 5)]
    v = [x/12.92 if x <= .04045 else ((x+.055)/1.055)**2.4 for x in v]
    return .2126*v[0] + .7152*v[1] + .0722*v[2]
def cr(a, b):
    x, y = sorted([lum(a), lum(b)], reverse=True); return (x+.05)/(y+.05)
BSTEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
BL = [.975, .95, .89, .82, .72, .62, .53, .45, .37, .29, .22]
BF = [.25, .4, .6, .8, .95, 1, 1, .95, .85, .7, .6]
NSTEPS = [0, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950, 1000]
NL = [.995, .975, .95, .91, .85, .72, .60, .50, .41, .32, .25, .20, .14]
ROUTES = {  # id: (brand, label, brand hue, chroma, neutral hue, neutral chroma, light-mode primary step)
    'copper':  ('aid-iot', 'Copper', 45, .13, 75, .008, 600),
    'indigo':  ('aid-iot', 'Indigo', 275, .15, 75, .008, 600),
    'jamun':   ('aid-iot', 'Jamun', 340, .12, 75, .008, 600),
    'brass':   ('aid-defence', 'Slate & Brass', 85, .10, 240, .02, 700),
    'glacier': ('aid-defence', 'Graphite & Glacier', 215, .07, 260, .006, 700),
    'bone':    ('aid-defence', 'Basalt & Bone', 85, .025, 200, .018, 800),
}
css, report = ['/* Generated by routes.py. Identity round 1 colour routes as brand-library overrides. */'], []
for rid, (brand, label, h, c, nh, nc, pstep) in ROUTES.items():
    B = {s: gamut(L, c*f, h) for s, L, f in zip(BSTEPS, BL, BF)}
    N = {s: gamut(L, nc * (0 if s in (0,) else 1), nh) for s, L in zip(NSTEPS, NL)}
    prim = B[pstep]; hov = B[{600: 700, 700: 800, 800: 900}[pstep]]
    v = {f'--aid-color-neutral-{s}': N[s] for s in NSTEPS}
    v.update({
        '--aid-brand-color-primary-base': prim, '--aid-brand-color-primary-hover': hov,
        '--aid-brand-color-primary-subtle': B[100], '--aid-brand-color-primary-on': N[0],
        '--aid-brand-color-primary-dark-base': B[300], '--aid-brand-color-primary-dark-hover': B[200],
        '--aid-brand-color-primary-dark-subtle': B[900], '--aid-brand-color-primary-dark-on': N[1000],
        '--aid-brand-color-accent-base': B[800], '--aid-brand-color-accent-on': N[0],
        '--aid-brand-color-accent-dark': B[200], '--aid-brand-color-accent-on-dark': N[1000],
        '--aid-brand-color-data-viz-1': B[500], '--aid-brand-color-data-viz-2': N[500], '--aid-brand-color-data-viz-3': B[300],
        '--aid-brand-color-data-viz-4': B[700], '--aid-brand-color-data-viz-5': N[300], '--aid-brand-color-data-viz-6': B[900],
    })
    v.update({f'--route-{s}': B[s] for s in BSTEPS})
    css.append(f'[data-brand="{brand}"][data-route="{rid}"] {{\n' + '\n'.join(f'  {k}: {x};' for k, x in v.items()) + '\n}')
    report.append(f"{label:20} light: white on primary {cr(N[0], prim):.2f} · link on canvas {cr(prim, N[50]):.2f} · text {cr(N[900], N[50]):.2f}"
                  f" | dark: on-action {cr(N[1000], B[300]):.2f} · link on surface {cr(B[300], N[900]):.2f} · text {cr(N[50], N[950]):.2f}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'routes.css'), 'w').write('\n\n'.join(css) + '\n')
print('\n'.join(report))
